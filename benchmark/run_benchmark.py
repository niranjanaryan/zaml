#!/usr/bin/env python3
"""Compares zamlpy against PyYAML and ruamel.yaml on the same YAML fixture.

The fixture is the 100k-key nested map generated by gen_big_yaml.py
(~15 MB). Each parser runs 3 times and the average is reported. A
correctness check compares the map size and first key/value against
PyYAML's CSafeLoader.
"""
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
BIG = REPO / "benchmark" / "big.yml"


def ensure_fixture() -> bytes:
    if not BIG.exists():
        print(f"Generating {BIG} ...")
        subprocess.check_call(
            [sys.executable, str(REPO / "benchmark" / "gen_big_yaml.py")]
        )
    return BIG.read_bytes()


def time_it(label, fn, n_runs=3):
    times = []
    result = None
    for _ in range(n_runs):
        t0 = time.perf_counter()
        result = fn()
        times.append((time.perf_counter() - t0) * 1000.0)
    avg = sum(times) / n_runs
    print(
        f"  {label:<38s} avg {avg:8.2f} ms  (min {min(times):.2f}, max {max(times):.2f})"
    )
    return avg, result


def main():
    contents = ensure_fixture()
    print(f"\nBenchmarking on {len(contents):,} byte YAML file\n")

    try:
        import zamlpy
    except ImportError:
        print("pip install zamlpy")
        sys.exit(1)

    try:
        import yaml as pyyaml
    except ImportError:
        print("pip install pyyaml ruamel.yaml")
        sys.exit(1)

    print("Python:")
    zamlpy_avg, zamlpy_results = time_it(
        "zamlpy", lambda: zamlpy.load(contents)
    )
    pyyaml_c_avg, pyyaml_c_results = time_it(
        "PyYAML CSafeLoader", lambda: pyyaml.load(contents, Loader=pyyaml.CSafeLoader)
    )
    pyyaml_avg, pyyaml_results = time_it(
        "PyYAML SafeLoader", lambda: pyyaml.load(contents, Loader=pyyaml.SafeLoader)
    )

    ruamel_avg = None
    try:
        from ruamel.yaml import YAML

        yaml = YAML(typ="safe", pure=True)
        ruamel_avg, _ = time_it(
            "ruamel.yaml (safe, pure Python)", lambda: yaml.load(contents)
        )
    except ImportError:
        print("  (ruamel.yaml not installed; skipping)")

    print()
    print("Summary (avg ms over 3 runs):")
    print(f"  zamlpy                    {zamlpy_avg:8.2f}")
    print(f"  PyYAML CSafeLoader        {pyyaml_c_avg:8.2f}")
    print(f"  PyYAML SafeLoader         {pyyaml_avg:8.2f}")
    if ruamel_avg is not None:
        print(f"  ruamel.yaml (safe)        {ruamel_avg:8.2f}")
    print()
    print(f"  zamlpy vs PyYAML C:   {pyyaml_c_avg / zamlpy_avg:5.2f}x")
    print(f"  zamlpy vs PyYAML Py:  {pyyaml_avg / zamlpy_avg:5.2f}x")
    if ruamel_avg is not None:
        print(f"  zamlpy vs ruamel:     {ruamel_avg / zamlpy_avg:5.2f}x")

    print()
    print("Correctness check:")
    expected_size = len(pyyaml_c_results)
    expected_first_key = min(pyyaml_c_results)
    expected_first_val = pyyaml_c_results[expected_first_key]
    print(
        f"  PyYAML  : size={expected_size}, first_key={expected_first_key!r}, first_value={expected_first_val!r}"
    )
    print(
        f"  zamlpy  : size={len(zamlpy_results)}, first_key={min(zamlpy_results)!r}, first_value={zamlpy_results[min(zamlpy_results)]!r}"
    )

    if (
        len(zamlpy_results) == expected_size
        and min(zamlpy_results) == expected_first_key
    ):
        print("  ✓ size and first key match")
    else:
        print("  ✗ MISMATCH")
        sys.exit(1)


if __name__ == "__main__":
    main()
